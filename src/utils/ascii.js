export function getFullNameAscii(cols = 80) {
  let lines;
  if (cols >= 104) {
    lines = BANNER_SLANT_FULL;
  } else if (cols >= 74) {
    lines = BANNER_SLANT_TWO_LINE;
  } else {
    lines = BANNER_SLANT_THREE_LINE;
  }

  return lines
    .map(line => {
      if (!line.trim()) return '';
      return ansi.bold(ansi.brightCyan(line));
    })
    .join('\n');
}

export const FULL_NAME_ASCII = BANNER_SLANT_FULL.join('\n');

export function toAscii(text) {
  return text;
}
